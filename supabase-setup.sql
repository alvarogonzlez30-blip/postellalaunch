-- POSTELLA FEST — tabla para el mural colaborativo en directo
create table if not exists public.postella_postcards (
  id bigint generated by default as identity primary key,
  message text not null check (char_length(message) between 1 and 120),
  created_at timestamptz not null default now()
);

alter table public.postella_postcards enable row level security;

-- La web puede leer postales y enviar nuevas postales sin registro.
-- Pensado para una presentación pública de clase; limita el acceso a esta tabla.
create policy "public can read postcards"
on public.postella_postcards for select
to anon
using (true);

create policy "public can send postcards"
on public.postella_postcards for insert
to anon
with check (char_length(message) between 1 and 120);

-- Activar eventos en tiempo real para esta tabla.
alter publication supabase_realtime add table public.postella_postcards;
